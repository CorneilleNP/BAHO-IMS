"""
Migrates historical cherry reception data out of a CWS reception/finance
workbook (the "Bugoyi CWS" format: a CHERRY RECEIVED sheet with Date,
Farmer details, Sector/Cell/Village, GRN, Good/Float cherry quantity +
price + transport + commission, Total qty/amount, Paid/Not paid) into
SQL matching packages/db/migrations/0001-0002.

Usage:
    python migrate_cherry_receipts.py <workbook.xlsx> <facility_code> <crop_year_label> > out.sql

This is a one-time, per-station, per-season ETL tool (not a live sync
path) — see "Parallel, non-blocking: historical Excel migration" in the
project plan. Run it once a Supabase/Postgres instance exists, review
the generated SQL, then apply it with psql.

Known limitations, call out before trusting the output on real data:
  - Farmer de-duplication is by (full_name, phone) only, since no
    national_id column exists in the source sheet. Two different
    farmers sharing a name+phone typo would incorrectly merge.
  - GRN numbers become a composite code (see numbering scheme in the
    project plan) rather than reusing the source sheet's small integer,
    which the source sheet only guaranteed unique per sheet, not
    globally across seasons/stations.
  - Excel's serial-date-vs-string-date inconsistency in the DATE column
    (observed in the real file) is handled by trying serial-number
    parsing first and falling back to text parsing, but any row that
    fails both is skipped and reported on stderr for manual fixing.
"""
import sys
from datetime import datetime, timedelta
from uuid import uuid4

import openpyxl

EXCEL_EPOCH = datetime(1899, 12, 30)  # Excel's day-0, accounting for its leap-year bug

SHEET_NAME = "CHERRY RECEIVED"
HEADER_ROWS = 4  # data starts on row 5 in the real workbook


def sql_str(value):
    if value is None or value == "":
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def sql_num(value):
    if value is None or value == "":
        return "0"
    return str(value)


def parse_date(raw):
    if raw is None or raw == "":
        return None
    if isinstance(raw, datetime):
        return raw
    if isinstance(raw, (int, float)):
        return EXCEL_EPOCH + timedelta(days=raw)
    text = str(raw).strip()
    for fmt in ("%d/%m/%Y", "%Y-%m-%d"):
        try:
            return datetime.strptime(text, fmt)
        except ValueError:
            continue
    return None


def main():
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(1)

    workbook_path, facility_code, crop_year_label = sys.argv[1:4]
    wb = openpyxl.load_workbook(workbook_path, data_only=True)
    sheet = wb[SHEET_NAME]

    farmer_keys_seen = {}  # (name, phone) -> farmer_id, de-dup within this run
    lines = []
    lines.append("-- Generated by tools/excel-migration/migrate_cherry_receipts.py")
    lines.append(f"-- Source: {workbook_path} / sheet '{SHEET_NAME}'")
    lines.append("begin;")
    lines.append(
        f"""
do $$
declare
  v_facility_id uuid;
  v_crop_year_id uuid;
begin
  select id into v_facility_id from facilities where code = {sql_str(facility_code)};
  select id into v_crop_year_id from crop_years where label = {sql_str(crop_year_label)};
  if v_facility_id is null then raise exception 'Unknown facility code {facility_code}'; end if;
  if v_crop_year_id is null then raise exception 'Unknown crop year {crop_year_label}'; end if;
end $$;
"""
    )

    skipped = 0
    inserted = 0
    seq = 0

    for row_idx, row in enumerate(
        sheet.iter_rows(min_row=HEADER_ROWS + 1, values_only=True), start=HEADER_ROWS + 1
    ):
        (
            date_raw, farmer_name, phone, email, sector, cell, village, grn,
            good_qty, good_price, good_transport, good_commission,
            float_qty, float_price, float_transport, float_commission,
            total_qty, total_amt, paid, not_paid, *_rest,
        ) = (list(row) + [None] * 24)[:24]

        if not farmer_name:
            continue

        received_at = parse_date(date_raw)
        if received_at is None:
            print(f"SKIP row {row_idx}: unparseable date {date_raw!r}", file=sys.stderr)
            skipped += 1
            continue

        farmer_key = (str(farmer_name).strip().upper(), str(phone or "").strip())
        if farmer_key not in farmer_keys_seen:
            farmer_id = str(uuid4())
            farmer_keys_seen[farmer_key] = farmer_id
            farmer_code = f"{facility_code}-{len(farmer_keys_seen):05d}"
            lines.append(
                "insert into farmers (id, farmer_code, full_name, phone, email, home_facility_id, is_active) "
                f"select {sql_str(farmer_id)}, {sql_str(farmer_code)}, {sql_str(farmer_name)}, "
                f"{sql_str(phone)}, {sql_str(email)}, id, true from facilities where code = {sql_str(facility_code)} "
                "on conflict (farmer_code) do nothing;"
            )
        farmer_id = farmer_keys_seen[farmer_key]

        seq += 1
        receipt_id = str(uuid4())
        # Composite GRN per the project's offline-safe numbering scheme;
        # original sheet's small integer GRN is kept in notes for traceability.
        grn_number = f"{facility_code}-{crop_year_label}-IMPORT-{seq:05d}"
        payment_status = "PAID" if (paid and not not_paid) else ("PARTIAL" if paid else "UNPAID")

        lines.append(
            "insert into cherry_receipts "
            "(id, grn_number, facility_id, farmer_id, crop_year_id, received_at, payment_status, notes) "
            f"select {sql_str(receipt_id)}, {sql_str(grn_number)}, id, {sql_str(farmer_id)}, "
            f"(select id from crop_years where label = {sql_str(crop_year_label)}), "
            f"{sql_str(received_at.isoformat())}, {sql_str(payment_status)}, "
            f"{sql_str(f'Imported from Excel. Original GRN: {grn}. Sector/Cell/Village: {sector}/{cell}/{village}')} "
            f"from facilities where code = {sql_str(facility_code)};"
        )

        if good_qty:
            lines.append(
                "insert into cherry_receipt_lines "
                "(cherry_receipt_id, cherry_grade, quantity_kg, farm_price_per_kg, transport_cost, commission) "
                f"values ({sql_str(receipt_id)}, 'GOOD', {sql_num(good_qty)}, {sql_num(good_price)}, "
                f"{sql_num(good_transport)}, {sql_num(good_commission)});"
            )
        if float_qty:
            lines.append(
                "insert into cherry_receipt_lines "
                "(cherry_receipt_id, cherry_grade, quantity_kg, farm_price_per_kg, transport_cost, commission) "
                f"values ({sql_str(receipt_id)}, 'FLOAT', {sql_num(float_qty)}, {sql_num(float_price)}, "
                f"{sql_num(float_transport)}, {sql_num(float_commission)});"
            )

        if paid:
            lines.append(
                "insert into cherry_payments (cherry_receipt_id, paid_at, amount, method) "
                f"values ({sql_str(receipt_id)}, {sql_str(received_at.isoformat())}, {sql_num(paid)}, 'CASH');"
            )

        inserted += 1

    lines.append("commit;")
    print("\n".join(lines))
    print(f"-- {inserted} receipts imported, {skipped} rows skipped, {len(farmer_keys_seen)} unique farmers", file=sys.stderr)


if __name__ == "__main__":
    main()
